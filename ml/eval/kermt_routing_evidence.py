"""Per-endpoint serving choice (XGBoost or KERMT Tier-0) from the held-out test records.

Blueprint Module 8: the routing table says, per endpoint, which model serves it, "decided per
endpoint by the Module 11 comparison". This script applies one written rule to the records in
git and writes both the evidence table and the routing file the API reads.

The rule (fixed here, before the table is read):
  * Primary metric: AUROC for classification (higher is better), test MAE for regression (lower).
  * KERMT serves an endpoint only when it beats XGBoost on the primary metric by MORE than the
    larger of the two 5-seed standard deviations, AND, for classification, its raw Brier score is
    not worse than XGBoost's by more than the larger of the two Brier standard deviations.
  * Otherwise XGBoost serves it. XGBoost is the incumbent: cheaper (one ~10 ms forward per seed
    vs ~0.2 s), already carrying the held-out error band and the promoted AD index, so a tie or a
    loss stays on it.
  * Raw (uncalibrated) numbers only, matching what is served (C0, decisions.md 2026-10-08).

This is a routing decision, not a statement about molecules or a user-facing ranking: the client
never sees which model "won", only each row's `model_id` (AGENTS.md rule 3 is untouched).

Caveats carried into the evidence file (see `documentation/status/kermt_vs_xgboost_regression.md`):
the two sides trained on different pools (KERMT withholds a calibration split; DILI is the
non-augmented pool), and five seeds support a noise margin, not a significance test.

Usage (from ml/):
    PYTHONPATH=. ./.venv/Scripts/python.exe eval/kermt_routing_evidence.py
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ML = Path(__file__).resolve().parents[1]
REPO = ML.parent
KERMT_RESULTS = REPO / "documentation" / "status" / "kermt_tier0_results"
XGB_EVAL = ML / "runs" / "test_evaluations"
ROUTING_PATH = ML / "serve" / "routing.json"
EVIDENCE_PATH = REPO / "documentation" / "status" / "kermt_routing_evidence.md"

# Test-molecule identity (KERMT's test input contains every XGBoost test molecule, checked
# 2026-10-19 against `predictions/test/input/smiles.csv` of the seed-0 run-record artifacts and
# `ml/data/processed/20260830T200000Z/<endpoint>/test.csv`). toxicity__cls and dili_standalone__cls
# have no run-record artifact, so only the equal n_test is known.
TEST_SET_IDENTITY_VERIFIED = {
    "metabolism__cls", "metabolism__reg", "absorption_distribution__cls", "absorption_distribution__reg",
}


def load_pairs() -> list[dict]:
    rows = []
    for agg in sorted(KERMT_RESULTS.glob("*/aggregate_5seeds.json")):
        arm = agg.parent.name
        for endpoint, m in json.loads(agg.read_text(encoding="utf-8"))["test_metrics_across_seeds"].items():
            x = json.loads((XGB_EVAL / f"{endpoint}.json").read_text(encoding="utf-8"))
            rows.append({"endpoint": endpoint, "arm": arm, "task": m["task_type"], "k": m["raw"],
                         "x": x["aggregated_test_raw"], "n_test": x["n_test"]})
    return sorted(rows, key=lambda r: r["endpoint"])


def decide(row: dict) -> tuple[str, str]:
    k, x = row["k"], row["x"]
    if row["task"] == "classification":
        gap = k["auroc_mean"] - x["auroc_mean"]  # positive = KERMT higher
        margin = max(k["auroc_std"], x["auroc_std"])
        brier_gap = k["brier_score_mean"] - x["brier_score_mean"]  # positive = KERMT worse
        brier_margin = max(k["brier_score_std"], x["brier_score_std"])
        if gap <= margin:
            return "xgboost", f"AUROC gap {gap:+.4f} does not exceed the noise margin {margin:.4f}"
        if brier_gap > brier_margin:
            return "xgboost", f"AUROC gap {gap:+.4f} clears {margin:.4f} but Brier is worse by {brier_gap:.4f} (margin {brier_margin:.4f})"
        return "kermt", f"AUROC gap {gap:+.4f} exceeds {margin:.4f}; Brier (KERMT minus XGBoost) {brier_gap:+.4f} is within the {brier_margin:.4f} allowance"
    gap = x["mae_mean"] - k["mae_mean"]  # positive = KERMT lower error
    margin = max(k["mae_std"], x["mae_std"])
    if gap <= margin:
        return "xgboost", f"MAE reduction {gap:+.4f} does not exceed the noise margin {margin:.4f}"
    return "kermt", f"MAE reduction {gap:+.4f} exceeds the noise margin {margin:.4f}"


def render(rows: list[dict], decisions: dict[str, tuple[str, str]]) -> str:
    out = [
        "# KERMT vs XGBoost: per-endpoint serving choice",
        "",
        "Generated by `ml/eval/kermt_routing_evidence.py` from the 5-seed raw test records in git. It applies the rule in",
        "that file's docstring and writes `ml/serve/routing.json`. **This chooses which model serves an endpoint; it is not a",
        "quality ranking and no client ever sees a winner** (each row only carries its own `model_id`).",
        "",
        "| endpoint | KERMT arm | primary metric | KERMT | XGBoost | served by | reason |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        k, x = r["k"], r["x"]
        if r["task"] == "classification":
            metric, kv, xv = "test AUROC", f"{k['auroc_mean']:.4f} ± {k['auroc_std']:.4f}", f"{x['auroc_mean']:.4f} ± {x['auroc_std']:.4f}"
        else:
            metric, kv, xv = "test MAE", f"{k['mae_mean']:.4f} ± {k['mae_std']:.4f}", f"{x['mae_mean']:.4f} ± {x['mae_std']:.4f}"
        model, why = decisions[r["endpoint"]]
        out.append(f"| {r['endpoint']} | {r['arm']} | {metric} | {kv} | {xv} | **{model}** | {why} |")
    out += [
        "",
        "## Read this before relying on the table",
        "",
        "- **Pools differ.** KERMT withholds a calibration split and trains on fewer molecules; the grouped endpoints are one",
        "  multi-task model. `dili_standalone__cls` is the non-augmented pool (287 molecules) against XGBoost's augmented 979,",
        "  so DILI is not a like-for-like pair and stays on XGBoost unless KERMT clears the margin regardless.",
        "- **Same test molecules.** Verified for the four arms with run-record artifacts (12 of 14 endpoints): every XGBoost",
        "  test molecule is in KERMT's test input and the counts are equal. Not verified for `toxicity__cls` and",
        "  `dili_standalone__cls` (no record artifact); only the equal `n_test` is known there.",
        "- **Five seeds.** The margin is the larger of the two seed standard deviations, a noise allowance and not a significance test.",
        "- **HIA** has a 47-molecule calibration set; its raw metrics stand, its calibrated ones are not reportable (D4), and none is served.",
        "- Re-run this script whenever a model is retrained; commit `routing.json` with the table that produced it.",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if routing.json or the evidence file is stale")
    args = parser.parse_args(argv)

    rows = load_pairs()
    if len(rows) != 14:
        raise SystemExit(f"expected 14 endpoints, found {len(rows)}")
    decisions = {r["endpoint"]: decide(r) for r in rows}
    routing = {
        "version": 1,
        "rule": "ml/eval/kermt_routing_evidence.py",
        "default": "xgboost",
        "endpoints": {
            r["endpoint"]: {"model": decisions[r["endpoint"]][0], "kermt_arm": r["arm"], "reason": decisions[r["endpoint"]][1]}
            for r in rows
        },
    }
    routing_text = json.dumps(routing, indent=2, sort_keys=True) + "\n"
    evidence_text = render(rows, decisions)
    if args.check:
        stale = (not ROUTING_PATH.exists() or ROUTING_PATH.read_text(encoding="utf-8") != routing_text
                 or not EVIDENCE_PATH.exists() or EVIDENCE_PATH.read_text(encoding="utf-8") != evidence_text)
        print("routing evidence is " + ("STALE" if stale else "current"))
        return 1 if stale else 0
    ROUTING_PATH.write_text(routing_text, encoding="utf-8", newline="\n")
    EVIDENCE_PATH.write_text(evidence_text, encoding="utf-8", newline="\n")
    print(evidence_text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
