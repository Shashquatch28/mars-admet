"""Module 8 routing table: which model serves each endpoint.

`routing.json` (next to this file) is generated by `eval/kermt_routing_evidence.py` from the
held-out test records and committed with the evidence table that produced it. It is the
blueprint's "endpoint -> serving model" table. Two models exist today: the promoted XGBoost
seeds (always available in the API image) and the KERMT Tier-0 seeds (served by the separate
KERMT inference service, `serve/kermt_service/`).

Missing, unreadable or inconsistent routing never changes what is served silently: a table that
does not name all 14 ML endpoints, or names an unknown model or KERMT arm, is rejected at load.
When the KERMT service is not configured the table is simply not consulted (everything is XGBoost).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from mars_contracts.endpoints import ML_ENDPOINTS

DEFAULT_ROUTING_PATH = Path(__file__).resolve().parent / "routing.json"
MODELS = ("xgboost", "kermt")

# Tier-0 arm -> the endpoints (target order) its checkpoints predict. Mirrors each arm's
# `target_names` in the W&B artifact metadata; `KermtRouter` re-checks it against the service.
KERMT_ARMS: dict[str, tuple[str, ...]] = {
    "dili_standalone__cls": ("dili_liver_injury",),
    "toxicity__cls": ("herg_cardiotoxicity", "ames_mutagenicity"),
    "metabolism__cls": ("cyp3a4_inhibition", "cyp2d6_inhibition", "cyp2c9_inhibition"),
    "metabolism__reg": ("clearance_microsomal",),
    "absorption_distribution__cls": ("hia_absorption", "pgp_inhibition", "bbb_permeability"),
    "absorption_distribution__reg": ("solubility_logs", "lipophilicity_logp", "caco2_permeability", "ppb_binding"),
}


@dataclass(frozen=True)
class Route:
    endpoint: str
    model: str  # "xgboost" | "kermt"
    kermt_arm: str  # the arm that would serve it; meaningful when model == "kermt"
    reason: str


class RoutingTable:
    def __init__(self, routes: dict[str, Route]) -> None:
        self._routes = dict(routes)

    @classmethod
    def load(cls, path: Path | str | None = None) -> RoutingTable:
        path = Path(path) if path else DEFAULT_ROUTING_PATH
        raw = json.loads(path.read_text(encoding="utf-8"))
        if raw.get("version") != 1:
            raise ValueError(f"{path}: unsupported routing version {raw.get('version')!r}")
        default = raw.get("default", "xgboost")
        if default not in MODELS:
            raise ValueError(f"{path}: unknown default model {default!r}")
        expected = {e.value for e in ML_ENDPOINTS}
        listed = raw.get("endpoints", {})
        if set(listed) != expected:
            missing, extra = sorted(expected - set(listed)), sorted(set(listed) - expected)
            raise ValueError(f"{path}: routing must name exactly the 14 ML endpoints (missing {missing}, unexpected {extra})")
        routes: dict[str, Route] = {}
        for endpoint, entry in listed.items():
            model = entry.get("model", default)
            arm = entry.get("kermt_arm", "")
            if model not in MODELS:
                raise ValueError(f"{path}: {endpoint}: unknown model {model!r}")
            if arm not in KERMT_ARMS or endpoint not in KERMT_ARMS[arm]:
                raise ValueError(f"{path}: {endpoint}: {arm!r} is not a KERMT arm that predicts it")
            routes[endpoint] = Route(endpoint, model, arm, entry.get("reason", ""))
        return cls(routes)

    @classmethod
    def all_xgboost(cls) -> RoutingTable:
        arm_of = {e: arm for arm, eps in KERMT_ARMS.items() for e in eps}
        return cls({ep.value: Route(ep.value, "xgboost", arm_of[ep.value], "default") for ep in ML_ENDPOINTS})

    def route(self, endpoint_key: str) -> Route | None:
        return self._routes.get(endpoint_key)

    def kermt_endpoints(self, endpoint_keys: list[str]) -> list[str]:
        return [e for e in endpoint_keys if (r := self._routes.get(e)) is not None and r.model == "kermt"]

    def kermt_endpoint_set(self) -> frozenset[str]:
        return frozenset(e for e, r in self._routes.items() if r.model == "kermt")

    def arms_for(self, endpoint_keys: list[str]) -> list[str]:
        """The distinct KERMT arms needed for these endpoints: one inference call per arm."""
        return sorted({self._routes[e].kermt_arm for e in self.kermt_endpoints(endpoint_keys)})

    def as_dict(self) -> dict[str, str]:
        return {e: r.model for e, r in sorted(self._routes.items())}
